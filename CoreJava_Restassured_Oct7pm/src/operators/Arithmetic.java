package operators;

public class Arithmetic {

	public static void main(String[] args) {
		
//		int a=20,b=10;
//		 a=50; b=40;
		float a=22.3f,b=33.3f;
		 System.out.println("a:"+a);
		 System.out.println("b:"+b);
		//Here a,b are normal variables
		//Re-Declaration is not possible[Duplicate local variable]
		//Re-Initialization is possible
		//More than one value storing is not possible
		 
		System.out.println(a+b);
		System.out.println(a-b);
		System.out.println(a*b);
		System.out.println(a/b);
		System.out.println(a%b);
		System.out.println("==========");
		
		System.out.println(8+3);
		System.out.println(8-3);
		System.out.println(8*3);
		System.out.println(8/3);
		System.out.println(8%3);
		
	}

}
